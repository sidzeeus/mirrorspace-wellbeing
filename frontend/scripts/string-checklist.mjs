/**
 * Writes the checklist of every string on the safety-critical screens into
 * docs/review-needed.md, between the two marker comments. Run after changing any of
 * these message files:  node scripts/string-checklist.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.resolve(root, "..", "docs", "review-needed.md");
const SCREENS = [
  ["support", "Support (SOS) screen"],
  ["plan", "Safety plan screen"],
  ["resources", "Helplines screen"],
  ["offline", "Offline fallback screen"],
  ["sharing", "Sharing and consent screens"],
  ["contact", "Pages a trusted contact sees"],
  ["chat", "Chat screen"],
];

function flatten(tree, prefix = "") {
  return Object.entries(tree).flatMap(([key, value]) =>
    key.startsWith("_")
      ? []
      : typeof value === "string"
        ? [[`${prefix}${key}`, value]]
        : flatten(value, `${prefix}${key}.`),
  );
}

let block = "";
for (const [name, title] of SCREENS) {
  let messages;
  try {
    messages = JSON.parse(readFileSync(path.join(root, "messages", "en", `${name}.json`), "utf8"));
  } catch {
    continue;
  }
  block += `\n### ${title} (\`frontend/messages/en/${name}.json\`)\n\n`;
  block += "| Key | Text | Reviewed by / date |\n|---|---|---|\n";
  for (const [key, text] of flatten(messages)) {
    block += `| \`${key}\` | ${text.replaceAll("|", "\\|")} | |\n`;
  }
}

const START = "<!-- string-checklist:start -->";
const END = "<!-- string-checklist:end -->";
let doc = readFileSync(target, "utf8");
const generated = `${START}\nNEEDS_HUMAN_REVIEW. Generated by \`frontend/scripts/string-checklist.mjs\`. Do not edit by hand; edit the message file and run the script.\n${block}\n${END}`;
doc = doc.includes(START)
  ? doc.slice(0, doc.indexOf(START)) + generated + doc.slice(doc.indexOf(END) + END.length)
  : `${doc.trimEnd()}\n\n${generated}\n`;
writeFileSync(target, doc);
console.log("Updated docs/review-needed.md");
